#!/bin/sh
# nginx in front of EdgeShell: the only container with published ports.
#
# The site config is generated from EDGESHELL_DOMAIN and kept current:
#   no domain (empty or ":80")   plain HTTP on the server's IP, any Host
#   domain, no certificate yet   HTTP, plus the ACME challenge for certbot
#   domain with a certificate    HTTPS for the domain; HTTP and the bare IP
#                                redirect to it
# EDGESHELL_DOMAIN may also be the server's public IPv4 address: certbot then
# gets a short-lived Let's Encrypt certificate for the IP itself.
#
# Logs go to stdout (docker logs) and to /var/log/edgeshell-nginx, which the
# host's fail2ban reads (docker/host-hardening.sh).
# A watcher re-renders every 30 s and reloads nginx when anything changed
# (new or renewed certificate, domain added), so no restart is needed.
set -eu

SITE=/etc/nginx/conf.d/default.conf
APP=/etc/nginx/edgeshell-app.conf
LE=/etc/letsencrypt/live

domain() {
    case "${EDGESHELL_DOMAIN:-}" in
        ""|":80"|":443") echo "" ;;
        *) echo "$EDGESHELL_DOMAIN" | tr -cd 'A-Za-z0-9.-' ;;
    esac
}

write_app() {
    # Shared by every server block: proxy to the app, hardened headers,
    # rate limit on sign-in and recovery form posts.
    cat > "$APP" <<'EOF'
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "SAMEORIGIN" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;

location /.well-known/acme-challenge/ {
    root /var/www/certbot;
    default_type text/plain;
}

# Hidden files are never served.
location ~ /\.(?!well-known) {
    return 404;
}

location ~ ^/(login|recover|forgot|signup|reset/) {
    limit_req zone=edgeshell_auth burst=20 nodelay;
    proxy_pass http://edgeshell;
    include /etc/nginx/edgeshell-proxy.conf;
}

location / {
    proxy_pass http://edgeshell;
    include /etc/nginx/edgeshell-proxy.conf;
}
EOF
    cat > /etc/nginx/edgeshell-proxy.conf <<'EOF'
proxy_http_version 1.1;
proxy_set_header Connection "";
proxy_set_header Host $host;
proxy_set_header X-Real-IP $remote_addr;
# Overwrite, never append: clients cannot forge their address for the
# lockout, rate limits and audit log.
proxy_set_header X-Forwarded-For $remote_addr;
proxy_set_header X-Forwarded-Proto $scheme;
proxy_set_header X-Forwarded-Host $host;
proxy_hide_header Server;
proxy_hide_header X-Powered-By;
proxy_read_timeout 600s;
proxy_send_timeout 600s;
EOF
}

render() {
    d="$(domain)"
    cat <<'EOF'
# Generated by docker/nginx/entrypoint.sh. Do not edit.
server_tokens off;
client_max_body_size 500m;
access_log /var/log/edgeshell-nginx/access.log combined;
error_log /var/log/edgeshell-nginx/error.log warn;
upstream edgeshell {
    server edgeshell:5000;
    keepalive 16;
}
# Only form posts count, so page loads never trip the limit.
map $request_method $edgeshell_post {
    POST    $binary_remote_addr;
    default "";
}
limit_req_zone $edgeshell_post zone=edgeshell_auth:10m rate=10r/m;
limit_req_status 429;
EOF
    if [ -n "$d" ] && [ -s "$LE/$d/fullchain.pem" ] && [ -s "$LE/$d/privkey.pem" ]; then
        # The certificate's timestamp is part of the output, so a renewal
        # changes it and triggers a reload.
        echo "# certificate: $d $(stat -c %Y "$LE/$d/fullchain.pem")"
        cat <<EOF
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;
    location /.well-known/acme-challenge/ { root /var/www/certbot; default_type text/plain; }
    # Answered here, not redirected, so the container health check never
    # depends on the public address or the certificate.
    location = /healthz { access_log off; proxy_pass http://edgeshell; include /etc/nginx/edgeshell-proxy.conf; }
    location / { return 301 https://$d\$request_uri; }
}
server {
    listen 443 ssl default_server;
    listen [::]:443 ssl default_server;
    http2 on;
    server_name $d;
    ssl_certificate     $LE/$d/fullchain.pem;
    ssl_certificate_key $LE/$d/privkey.pem;
    # Mozilla "intermediate" profile: TLS 1.2 and 1.3, forward secrecy and
    # AEAD ciphers only. Let's Encrypt no longer runs OCSP, so no stapling.
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305;
    ssl_ecdh_curve X25519:prime256v1:secp384r1;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:edgeshell_tls:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;
    if (\$host != "$d") { return 301 https://$d\$request_uri; }
    add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;
    add_header Cross-Origin-Opener-Policy "same-origin" always;
    include $APP;
}
EOF
    else
        [ -n "$d" ] && echo "# waiting for a certificate for $d (certbot)"
        cat <<EOF
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;
    include $APP;
}
EOF
    fi
}

mkdir -p /var/log/edgeshell-nginx
write_app
render > "$SITE"
nginx -t -q

(
    while sleep 30; do
        render > /tmp/edgeshell-site.new 2>/dev/null || continue
        if ! cmp -s /tmp/edgeshell-site.new "$SITE"; then
            cp "$SITE" /tmp/edgeshell-site.old
            cp /tmp/edgeshell-site.new "$SITE"
            if nginx -t -q 2>/dev/null; then
                nginx -s reload && echo "edgeshell: configuration updated ($(grep -m1 -E '^# (certificate|waiting)' "$SITE" || echo 'HTTP on any address'))"
            else
                cp /tmp/edgeshell-site.old "$SITE"
                echo "edgeshell: new configuration failed nginx -t; kept the previous one" >&2
            fi
        fi
    done
) &

exec nginx -g 'daemon off;'
