"""Build the in-app API guide (API page, "API guide") from docs/API.md.

The image ships no docs and no Markdown library, so the guide is rendered
here, at development time, into a template fragment. CI runs this with
--check and fails when the fragment no longer matches docs/API.md, so the two
never drift apart.

    pip install markdown==3.7
    python tools/build_api_guide.py           # rewrite the fragment
    python tools/build_api_guide.py --check   # exit 1 if it is out of date
"""
import os
import re
import sys

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'API.md')
OUT = os.path.join(ROOT, 'app', 'templates', 'account', '_api_guide_body.html')
REPO = 'https://github.com/855princekumar/edgeshell/blob/main/'


def build():
    with open(SRC, encoding='utf-8') as f:
        text = f.read()
    md = markdown.Markdown(extensions=['tables', 'fenced_code', 'toc', 'sane_lists'],
                           extension_configs={'toc': {'toc_depth': '2-3', 'permalink': False}})
    body = md.convert(text)
    # Links to other repository files point at GitHub; in-page anchors stay.
    body = re.sub(r'href="(?!https?:|#|mailto:)([^"]+)"',
                  lambda m: f'href="{REPO}docs/{m.group(1)}" target="_blank" rel="noopener"', body)
    body = body.replace('<table>', '<div class="table-responsive"><table class="table table-sm">') \
               .replace('</table>', '</table></div>')
    return ('{# Generated by tools/build_api_guide.py from docs/API.md. Do not edit. #}\n'
            '{% raw %}\n<nav class="guide-toc">' + md.toc + '</nav>\n<article class="guide">\n'
            + body + '\n</article>\n{% endraw %}\n')


def main():
    html = build()
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current.replace('\r\n', '\n') != html:          # a Windows checkout may use CRLF
            print('The in-app API guide is out of date: run python tools/build_api_guide.py')
            sys.exit(1)
        print('API guide matches docs/API.md')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
